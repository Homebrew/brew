# typed: strict
# frozen_string_literal: true

require "formula_versions"

#
# {CaskDescriptionCacheStore} provides methods to fetch and mutate cask descriptions used
# by the `brew desc` and `brew search` commands.
#
class CaskDescriptionCacheStore < DescriptionCacheStore
  Key = type_member { { fixed: String } }
  Value = type_member { { fixed: T.anything } }

  private

  sig { override.returns(Symbol) }
  def trust_type = :cask

  public

  # If the database is empty `update!` it with all known casks.
  #
  # @return [nil]
  sig { override.void }
  def populate_if_empty!
    return unless database.empty?

    Cask::Cask.all
              .each { |c| update!(c.full_name, [c.name.join(", "), c.desc.presence]) }
  end

  # Use an update report to update a populated {CaskDescriptionCacheStore}.
  #
  # @param report [Report] an update report generated by cmd/update.rb
  # @return [nil]
  sig { override.params(report: ReporterHub).void }
  def update_from_report!(report)
    return if database.empty? || report.empty?

    renamings = T.cast(report.select_formula_or_cask(:RC), T::Array[[String, String]])
    alterations = T.cast(
      report.select_formula_or_cask(:AC) +
      report.select_formula_or_cask(:MC) +
      renamings.filter_map(&:last),
      T::Array[String],
    )
    deletions = T.cast(report.select_formula_or_cask(:DC) + renamings.filter_map(&:first), T::Array[String])

    update_from_cask_tokens!(alterations)
    delete_from_cask_tokens!(deletions)
  end

  # Use an array of cask tokens to update a populated {CaskDescriptionCacheStore}.
  #
  # @param cask_tokens [Array] the casks to update
  # @return [nil]
  sig { params(cask_tokens: T::Array[String]).void }
  def update_from_cask_tokens!(cask_tokens)
    return if database.empty?

    cask_tokens.each do |token|
      c = Cask::CaskLoader.load(token)
      update!(c.full_name, [c.name.join(", "), c.desc.presence])
    rescue Cask::CaskUnavailableError, Homebrew::UntrustedTapError, *FormulaVersions::IGNORED_EXCEPTIONS
      delete!(token)
    end
  end
end
