# typed: strict
# frozen_string_literal: true

require "cache_store"
require "formula_versions"
require "trust"

#
# {DescriptionCacheStore} provides methods to fetch and mutate formula descriptions used
# by the `brew desc` and `brew search` commands.
#
class DescriptionCacheStore < CacheStore
  Key = type_member { { fixed: String } }
  Value = type_member { { fixed: T.anything } }

  # Inserts a formula description into the cache if it does not exist or
  # updates the formula description if it does exist.
  #
  # @param formula_name [String] the name of the formula to set
  # @param description  [String] the description from the formula to set
  # @return [nil]
  sig { params(formula_name: String, description: T.anything).void }
  def update!(formula_name, description)
    database.set(formula_name, description)
  end

  # Delete the formula description from the {DescriptionCacheStore}.
  #
  # @param formula_name [String] the name of the formula to delete
  # @return [nil]
  sig { params(formula_name: String).void }
  def delete!(formula_name)
    database.delete(formula_name)
  end

  # If the database is empty `update!` it with all known formulae.
  #
  # @return [nil]
  sig { void }
  def populate_if_empty!
    return unless database.empty?

    Formula.all.each { |formula| update!(formula.full_name, formula.desc) }
  end

  # Use an update report to update a populated {DescriptionCacheStore}.
  #
  # @param report [Report] an update report generated by cmd/update.rb
  # @return [nil]
  sig { params(report: ReporterHub).void }
  def update_from_report!(report)
    return if database.empty? || report.empty?

    renamings = T.cast(report.select_formula_or_cask(:R), T::Array[[String, String]])
    alterations = T.cast(
      report.select_formula_or_cask(:A) +
      report.select_formula_or_cask(:M) +
      renamings.filter_map(&:last),
      T::Array[String],
    )
    deletions = T.cast(
      report.select_formula_or_cask(:D) + renamings.filter_map(&:first),
      T::Array[String],
    )

    update_from_formula_names!(alterations)
    delete_from_formula_names!(deletions)
  end

  # Use an array of formula names to update a populated {DescriptionCacheStore}.
  #
  # @param formula_names [Array] the formulae to update
  # @return [nil]
  sig { params(formula_names: T::Array[String]).void }
  def update_from_formula_names!(formula_names)
    return if database.empty?

    formula_names.each do |name|
      update!(name, Formula[name].desc)
    rescue FormulaUnavailableError, Homebrew::UntrustedTapError, *FormulaVersions::IGNORED_EXCEPTIONS
      delete!(name)
    end
  end

  # Use an array of formula names to delete them from the {DescriptionCacheStore}.
  #
  # @param formula_names [Array] the formulae to delete
  # @return [nil]
  sig { params(formula_names: T::Array[String]).void }
  def delete_from_formula_names!(formula_names)
    return if database.empty?

    formula_names.each { delete!(it) }
  end
  alias delete_from_cask_tokens! delete_from_formula_names!

  # `select` trusted entries from the underlying database.
  sig { params(block: T.proc.params(arg0: Key, arg1: Value).returns(BasicObject)).returns(T::Hash[Key, Value]) }
  def select(&block)
    unless Homebrew::EnvConfig.no_require_tap_trust?
      untrusted_names = []
      database.each_key do |name|
        next unless Utils.full_name?(name)
        next if Homebrew::Trust.trusted?(trust_type, name)

        untrusted_names << name
      end
      delete_from_formula_names!(untrusted_names) if untrusted_names.present?
    end

    database.select(&block)
  end

  private

  sig { overridable.returns(Symbol) }
  def trust_type = :formula
end
require "description_cache_store/cask_description_cache_store"
